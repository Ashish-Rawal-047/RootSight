@dataclass
class Recommendation:
    recommendation_id: str
    playbook_id: str
    title: str
    action_type: str
    targets_hypothesis: str
    targets_driver: str
    score: float
    score_components: dict
    identification_cap: float
    cost_band: str
    reversibility: str
    time_to_impact_days: list[int]
    resource_dimension: str
    owner: str
    persona_framing: str
    conditional_on: list[str]
    conflicts_with: list[str] = field(default_factory=list)
    catalogue_version: str = CATALOGUE_VERSION

    def as_dict(self) -> dict:
        return asdict(self)


class RecommendationEngine:
    def recommend(self, *, hypotheses: list[dict], materiality: dict[str, dict],
                  persona_id: str, top_n: int = 3) -> list[Recommendation]:
        out: list[Recommendation] = []
        for h in hypotheses:
            hid = h["hypothesis_id"]
            mat = materiality.get(hid) or {}
            licensed = mat.get("action_type", "NO_ACTION")
            if licensed == "NO_ACTION":
                continue
            allowed_types = {
                "REMEDIATE": {"REMEDIATE"},
                "REMEDIATE_WITH_MONITORING": {"REMEDIATE", "MONITOR"},
                "INVESTIGATE": {"INVESTIGATE", "MONITOR"},
                "MONITOR": {"MONITOR"},
            }.get(licensed, {"MONITOR"})
            cap = IDENTIFICATION_CAP.get(h["causal_status"], 0.15)
            for pb in PLAYBOOKS:
                if persona_id not in pb.personas:
                    continue
                if pb.action_type not in allowed_types:
                    continue
                if pb.targets_driver not in ("*", h["driver_id"]):
                    continue
                benefit = min(pb.impact_index, cap)          # CEILING, not a multiplier
                cost = (pb.direct_cost_index + pb.effort_index +
                        pb.opportunity_cost_index) / 3.0
                risk = pb.irreversibility * pb.downside_exposure
                score = benefit - cost - risk
                comps = {
                    "impact_index": pb.impact_index,
                    "identification_cap": cap,
                    "expected_benefit": round(benefit, 4),
                    "benefit_rule": ("min(impact_index, identification_cap) - the cap is "
                                     "a ceiling, so weak identification cannot be "
                                     "outvoted by a large impact index"),
                    "expected_cost": round(cost, 4),
                    "cost_rule": "mean(direct_cost, effort, opportunity_cost)",
                    "risk_penalty": round(risk, 4),
                    "risk_rule": "irreversibility x downside_exposure",
                    "licensed_action_type": licensed,
                    "materiality_priority": mat.get("decision_priority"),
                    "time_to_impact_reported_separately": list(pb.time_to_impact_days),
                }
                out.append(Recommendation(
                    recommendation_id=f"REC-{hid}-{pb.playbook_id}",
                    playbook_id=pb.playbook_id, title=pb.title,
                    action_type=pb.action_type, targets_hypothesis=hid,
                    targets_driver=pb.targets_driver, score=round(score, 4),
                    score_components=comps, identification_cap=cap,
                    cost_band=pb.cost_band,
                    reversibility=("HIGH" if pb.irreversibility < 0.1 else
                                   "MEDIUM" if pb.irreversibility < 0.3 else "LOW"),
                    time_to_impact_days=list(pb.time_to_impact_days),
                    resource_dimension=pb.resource_dimension, owner=pb.owner,
                    persona_framing=pb.framing.get(persona_id, ""),
                    conditional_on=list(pb.evidence_requirements)))

        out.sort(key=lambda r: -r.score)
        out = out[:top_n]
        self._flag_conflicts(out)
        return out

    @staticmethod
    def _flag_conflicts(recs: list[Recommendation]) -> None:
        by_dim: dict[str, list[Recommendation]] = {}
        for r in recs:
            by_dim.setdefault(r.resource_dimension, []).append(r)
        for dim, group in by_dim.items():
            if len(group) > 1:
                for r in group:
                    r.conflicts_with = [o.recommendation_id for o in group
                                        if o.recommendation_id != r.recommendation_id]

    @staticmethod
    def catalogue() -> list[dict]:
        return [{"playbook_id": p.playbook_id, "title": p.title,
                 "action_type": p.action_type, "targets_driver": p.targets_driver,
                 "personas": list(p.personas), "owner": p.owner,
                 "cost_band": p.cost_band,
                 "time_to_impact_days": list(p.time_to_impact_days)}
                for p in PLAYBOOKS]
