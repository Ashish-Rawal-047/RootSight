"""Recommendation engine: versioned playbook catalogue + decision-theoretic scoring.

Recommendations are never generated by a model.  They are selected from a
catalogue an accountable human owns, and the model at most phrases them.

Two rules that matter more than the arithmetic:

  1. THE LICENSED ACTION TYPE IS A HARD FILTER.  The materiality engine decides
     whether the evidence licenses REMEDIATE, INVESTIGATE or MONITOR.  A remedial
     playbook cannot surface against an unidentified hypothesis no matter how
     large the exposure, because spending money to fix an unestablished mechanism
     is a gamble, not a decision.  The engine offers INVESTIGATE actions instead:
     buying information is the correct response to a big unidentified number.

  2. THE IDENTIFICATION CAP IS A CEILING, NOT A MULTIPLIER.  V4 said the cap was
     a max() and then implemented a product.  Here the benefit term is
     min(impact, cap): a high-impact action attached to weak identification
     cannot outscore a modest action attached to a solid one.

Persona changes which playbooks are visible and how they are framed - an
operations manager gets capacity actions at warehouse level, a CFO gets exposure
and disclosure actions.  Neither sees the other's.
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict

